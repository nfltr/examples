"""Write the measured sections of README.md and MIGRATION.md.

report.py <results.json> [<results.json> ...]

The diff numbers come from migration.patch; everything else from one or
more runs of `make dotnet-fleet` (scripts/test-dotnet-fleet.sh
prints where each run's results.json is). Each section sits between
`<!-- BEGIN generated by test/report.py: <name> -->` and its END marker;
nothing outside them is touched.
"""
import json
import os
import re
import sys

EX = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# What each file of the patch is. A file the patch touches that is not
# here fails the report, so the table stays complete.
FILES = {
    "agent/Program.cs": ("app", "the session's channel is the sidecar's endpoint; Agent.Execute served on loopback (a); the owned sidecar"),
    "controlplane/Program.cs": ("app", "the (a) channel registration; its header comment (the listeners are config)"),
    "shared/ControlPlaneChannel.cs": ("app", "the TLS client: trust of the fleet's private CA, the server-name check, HTTP/2 keepalive, connect timeout"),
    "shared/SidecarChannel.cs": ("app", "a channel to a sidecar endpoint: unix socket, named pipe or loopback TCP"),
    "controlplane/AgentChannels.cs": ("optional", "(a) a channel to an agent by name: a mapping or nfltr cat pipe"),
    "shared/DialChannel.cs": ("optional", "(a) without a mapping: one nfltr cat pipe child per connection"),
    "agent/OwnedSidecar.cs": ("optional", "the agent starts and owns its sidecar"),
    "shared/Job.cs": ("optional", "Windows: owned sidecar and dial children die with the agent"),
    "agent/appsettings.json": ("config", "the control plane's URL, CA, server name and keepalive become one local endpoint; the loopback Execute listener (a)"),
    "controlplane/appsettings.json": ("config", "the public TLS listener, its certificate and keepalive become a loopback listener; the agents' mappings (a)"),
    "sidecar/edge-agent.yaml": ("config", "new: the agent's sidecar"),
    "sidecar/controlplane.yaml": ("config", "new: the control plane's sidecar"),
}
CATEGORY = {"app": "app code, adding nfltr", "optional": "app code, optional new capabilities", "config": "configuration"}


def is_code(path, line):
    s = line.strip()
    if not s:
        return False
    if path.endswith(".cs"):
        return not s.startswith("//")
    if path.endswith(".yaml"):
        return not s.startswith("#")
    return True


def parse_patch():
    files, cur = [], None
    for line in open(os.path.join(EX, "migration.patch")):
        m = re.match(r"diff --git a/(?:app|with-nfltr)/(\S+) b/(?:app|with-nfltr)/(\S+)", line)
        if m:
            cur = {"path": m.group(2), "change": "modified", "add": 0, "del": 0, "add_code": 0, "del_code": 0, "hunks": []}
            files.append(cur)
            continue
        if line.startswith("new file"):
            cur["change"] = "new"
        elif line.startswith("deleted file"):
            cur["change"] = "deleted"
        elif line.startswith(("+++", "---", "index ")):
            continue
        elif line.startswith("@@"):
            cur["hunks"].append(line)
        elif cur and cur["hunks"]:
            cur["hunks"].append(line)
            if line.startswith("+"):
                cur["add"] += 1
                cur["add_code"] += is_code(cur["path"], line[1:])
            elif line.startswith("-"):
                cur["del"] += 1
                cur["del_code"] += is_code(cur["path"], line[1:])
    unknown = [f["path"] for f in files if f["path"] not in FILES]
    if unknown:
        sys.exit(f"report.py: FILES has no entry for {unknown}")
    return files


def ms(v):
    return f"{v:.2f}" if isinstance(v, float) else str(v)


def bench_row(run, stack, via, agent, steps, fresh):
    for r in run["bench"]:
        if (r["stack"], r["via"], r["agent"], r["steps"], r["fresh"]) == (stack, via, agent, steps, fresh):
            return f"{ms(r['p50_ms'])} / {ms(r['p95_ms'])}"
    sys.exit(f"report.py: no bench row {stack} {via} {agent} steps={steps} fresh={fresh}")


def p50(run, stack, via, agent, steps):
    return next(r["p50_ms"] for r in run["bench"] if (r["stack"], r["via"], r["agent"], r["steps"], r["fresh"]) == (stack, via, agent, steps, False))


def section_diff(files, runs):
    out = ["| file | change | lines + / − | code lines + / − | what |", "|---|---|---|---|---|"]
    totals = {}
    for cat in CATEGORY:
        for f in (f for f in files if FILES[f["path"]][0] == cat):
            t = totals.setdefault(cat, {"files": 0, "add": 0, "del": 0, "add_code": 0, "del_code": 0})
            t["files"] += 1
            for k in ("add", "del", "add_code", "del_code"):
                t[k] += f[k]
            out.append(f"| `{f['path']}` | {f['change']} | +{f['add']} / −{f['del']} | +{f['add_code']} / −{f['del_code']} | {FILES[f['path']][1]} |")
    out += ["", "| | files | lines + / − | code lines + / − |", "|---|---|---|---|"]
    for cat, t in totals.items():
        out.append(f"| {CATEGORY[cat]} | {t['files']} | +{t['add']} / −{t['del']} | +{t['add_code']} / −{t['del_code']} |")
    applied = " and ".join(f"{r['migration']['apply_ms']} ms" for r in runs)
    out += ["", f"Code lines: without comments and blank lines. Unchanged: `proto/` and `common/` "
            f"(the protocol and the business logic), and both `.csproj` files. `migrate.sh` applied the "
            f"patch to a copy of `app/` in {applied} ({runs_label(runs)}) and checked that the result is "
            f"`with-nfltr/`; the test's with-nfltr stack is built from that result."]
    return "\n".join(out)


def section_code(files):
    out = []
    for path in ("agent/Program.cs", "agent/appsettings.json", "controlplane/Program.cs", "controlplane/appsettings.json"):
        f = next(f for f in files if f["path"] == path)
        out += [f"`{path}`:", "", "```diff"] + [h.rstrip("\n") for h in f["hunks"]] + ["```", ""]
    return "\n".join(out).rstrip()


def runs_label(runs):
    return "one run" if len(runs) == 1 else f"runs 1 to {len(runs)}"


def section_moving_parts(runs):
    b, a = runs[0]["stacks"]["app"], runs[0]["stacks"]["with-nfltr"]
    exposed = lambda s: sum(len(v) for v in s["listeners"].values())
    where = lambda s: ", ".join(f"{m} {' '.join(l)}" for m, l in s["listeners"].items() if l) or "none"
    proxied = lambda s: ", ".join(f"`{t}`" for t in sorted(s["site_proxy"]["connects"]))
    ready = lambda stack: " / ".join(f"{r['stacks'][stack]['ready_ms']} ms" for r in runs)
    rows = [
        ("TCP listeners on the fleet's machines that are not loopback", f"{exposed(b)} ({where(b)})", f"{exposed(a)}"),
        ("private CA (its key kept off the fleet) and the certificates it issued", f"{b['certificates']['ca']} CA, {b['certificates']['ca_issued']} certificate", "none"),
        ("machine certificate from the relay on every machine (nfltr renews it)", "no", "yes" if a.get("machine_certificates") else "no"),
        ("processes on the fleet's 4 machines (apps + sidecars)", f"{b['processes']['app']} + {b['processes']['sidecar']}", f"{a['processes']['app']} + {a['processes']['sidecar']}"),
        ("what edge-2's site proxy let through: CONNECT to", proxied(b), proxied(a)),
        ("the control plane calls an agent by name (a)", "no (UNIMPLEMENTED, checked)", "yes, by mapping or `nfltr cat pipe`"),
        (f"`docker compose up` to the first ok command on every agent, {runs_label(runs)} (with nfltr: the relay already up)", ready("app"), ready("with-nfltr")),
    ]
    out = ["| | the app on its own network setup (`app/`) | the app with nfltr (`with-nfltr/`) |", "|---|---|---|"]
    out += [f"| {r[0]} | {r[1]} | {r[2]} |" for r in rows]
    out += ["", "Listeners: read from `/proc/net/tcp` and `/proc/net/tcp6` of each fleet machine "
            "while it ran (with nfltr, the machines include their sidecars). The relay is not a fleet "
            "machine and is not counted: hosted, it is not the organization's to run; self-hosted, "
            "it is one public endpoint for every fleet of the account."]
    return "\n".join(out)


def section_measured(runs):
    rows = [
        ("(b) session, direct TLS (`app/`, the baseline)", "TLS to the control plane", "app", "session", "edge-1", 0, False),
        ("(b) session", "e2ee (control plane)", "with-nfltr", "session", "edge-1", 0, False),
        ("(a) mapping, warm channel", "e2ee (edge-1)", "with-nfltr", "mapping", "edge-1", 0, False),
        ("(a) mapping, warm channel", "plain (edge-3)", "with-nfltr", "mapping", "edge-3", 0, False),
        ("(a) mapping, new connection per call", "e2ee (edge-1)", "with-nfltr", "mapping", "edge-1", 0, True),
        ("(a) mapping, new connection per call", "plain (edge-3)", "with-nfltr", "mapping", "edge-3", 0, True),
        ("(a) `nfltr cat pipe`, warm channel", "e2ee (edge-1)", "with-nfltr", "dial", "edge-1", 0, False),
        ("(a) `nfltr cat pipe`, warm channel", "plain (edge-3)", "with-nfltr", "dial", "edge-3", 0, False),
        ("(a) `nfltr cat pipe`, new process per call", "e2ee (edge-1)", "with-nfltr", "dial", "edge-1", 0, True),
        ("(a) `nfltr cat pipe`, new process per call", "plain (edge-3)", "with-nfltr", "dial", "edge-3", 0, True),
        ("(b) session, 100 progress updates back to back, direct TLS (`app/`, the baseline)", "TLS to the control plane", "app", "session", "edge-1", 100, False),
        ("(b) session, 100 progress updates back to back", "e2ee (control plane)", "with-nfltr", "session", "edge-1", 100, False),
        ("(a) mapping, 100 progress updates back to back", "e2ee (edge-1)", "with-nfltr", "mapping", "edge-1", 100, False),
    ]
    cols = ["p50 / p95"] if len(runs) == 1 else [f"run {i + 1}" for i in range(len(runs))]
    out = ["| call | transport | " + " | ".join(cols) + " |", "|---|---|" + "---|" * len(cols)]
    for label, tr, *k in rows:
        out.append(f"| {label} | {tr} | " + " | ".join(bench_row(r, *k) for r in runs) + " |")
    over = lambda steps: " and ".join(f"{p50(r, 'with-nfltr', 'session', 'edge-1', steps) - p50(r, 'app', 'session', 'edge-1', steps):+.2f} ms" for r in runs)
    rec = {}
    for r in runs:
        for x in r["restarts"]:
            rec.setdefault(x["restart"], []).append(x)
    rng = lambda xs, k: f"{min(x[k] for x in xs)} to {max(x[k] for x in xs)}" if len(set(x[k] for x in xs)) > 1 else f"{xs[0][k]}"
    first = [s["first_progress_ms"] for r in runs for s in r["streams"]]
    result = [s["result_ms"] for r in runs for s in r["streams"]]
    out += [
        "",
        f"- **Overhead against the direct TLS connection**, p50 with nfltr minus p50 in `app/`, {runs_label(runs)}: "
        f"a (b) session call {over(0)} (two sidecars and the relay, E2EE on); with 100 progress "
        f"updates back to back {over(100)} (negative: faster with nfltr in that run).",
        f"- **Streaming**: a command doing 100 ms of work per step with 5 progress updates, both stacks, "
        f"every path: the first update arrived {min(first)} to {max(first)} ms after the call, "
        f"the result {min(result)} to {max(result)} ms after it: updates arrive as the agent sends them.",
        "- **Agent restart** (killed mid-command, the control plane's own retry every 250 ms; ms after "
        f"the kill, {runs_label(runs)}, Docker restarting the container included):",
        "",
        "  | restart | UNAVAILABLE after | first ok call started after |",
        "  |---|---|---|",
    ]
    names = {"app-restart-edge-2": "`app/`: edge-2's agent, (b) over TLS",
             "restart-edge-2": "with nfltr: edge-2's agent (its sidecar kept running), (b)",
             "restart-edge-1": "with nfltr: edge-1's agent and the sidecar it owns, (a) mapping"}
    for k, label in names.items():
        out.append(f"  | {label} | {rng(rec[k], 'unavailable_after_kill_ms')} | {rng(rec[k], 'ok_call_started_after_kill_ms')} |")
    return "\n".join(out)


def write(doc, sections):
    path = os.path.join(EX, doc)
    text = open(path).read()
    for name, body in sections.items():
        pat = re.compile(r"(<!-- BEGIN generated by test/report.py: %s -->\n).*?(<!-- END generated: %s -->)" % (name, name), re.S)
        if not pat.search(text):
            sys.exit(f"report.py: no {name} markers in {doc}")
        text = pat.sub(lambda m: m.group(1) + body + "\n" + m.group(2), text)
    open(path, "w").write(text)
    print(f"wrote {path}")


if len(sys.argv) < 2:
    sys.exit(__doc__)
runs = [json.load(open(p)) for p in sys.argv[1:]]
files = parse_patch()
write("MIGRATION.md", {"diff": section_diff(files, runs), "code": section_code(files), "moving-parts": section_moving_parts(runs)})
write("README.md", {"measured": section_measured(runs), "moving-parts": section_moving_parts(runs)})
